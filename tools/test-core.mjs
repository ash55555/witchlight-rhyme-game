// Quick checks for the rhyme engine and game rules. Run: node tools/test-core.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';
const C = createRequire(import.meta.url)('../core.js');
C.loadDictionary(fs.readFileSync(new URL('../dict.txt', import.meta.url), 'utf8'));
let pass = 0, fail = 0;
const t = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); ok ? pass++ : (fail++, console.log('FAIL', name, 'got', got, 'want', want)); };
const ans = (seed, text, used = new Set([seed])) => { const r = C.checkAnswer(C.makeSeed(seed), text, used); return r.ok ? 'ok' : r.kind; };

t('toilet / boil it (the example)', ans('toilet', 'boil it'), 'ok');
t('toilet / spoil it', ans('toilet', 'spoil it'), 'ok');
t('toilet / foil it', ans('toilet', 'foil it'), 'ok');
t('toilet / boil (too short)', ans('toilet', 'boil'), 'wrong');
t('toilet / cat', ans('toilet', 'cat'), 'wrong');
t('cat / hat', ans('cat', 'hat'), 'ok');
t('cat / bat', ans('cat', 'bat'), 'ok');
t('cat / dog', ans('cat', 'dog'), 'wrong');
t('cat / cat repeated', ans('cat', 'cat'), 'used');
t('night / knight (same sound)', ans('night', 'knight'), 'same');
t('night / light', ans('night', 'light'), 'ok');
t('night / write', ans('night', 'write'), 'ok');
t('moon / balloon', ans('moon', 'balloon'), 'ok');
t('moon / soon', ans('moon', 'soon'), 'ok');
t('moon / moon river (ends in new word)', ans('moon', 'swoon'), 'ok');
t('not a real word', ans('cat', 'blorpzzle'), 'notword');
t('phrase with fake word', ans('cat', 'blorp hat'), 'notword');
t('empty', ans('cat', '   '), 'empty');
t('plural: cat / hats vs cats', ans('cat', 'hats'), 'wrong');
t('tea / see', ans('tea', 'see'), 'ok');
t('tea / key', ans('tea', 'key'), 'ok');
t('moon / hat', ans('moon', 'hat'), 'wrong');
t('uppercase + punctuation', ans('cat', 'Hat!!'), 'ok');
t('toilet: boil it then spoil it (same ending word, different phrase)', ans('toilet','spoil it',new Set(['toilet','boil it'])), 'ok');
t('toilet: boil it twice', ans('toilet','Boil it!',new Set(['toilet','boil it'])), 'used');
t('used word blocked', ans('cat', 'hat', new Set(['cat', 'hat'])), 'used');
t('flame / game', ans('flame', 'game'), 'ok');
t('bell / tell', ans('bell', 'tell'), 'ok');
t('ring / sing', ans('ring', 'sing'), 'ok');
t('sky / pie', ans('sky', 'pie'), 'ok');
t('sky / high', ans('sky', 'high'), 'ok');
t('too many words', ans('cat', 'a b c d e hat'), 'long');

// game rules
const ev = (o, ts) => ({ ts, ...o });
let st = C.initialState(), T = 1000;
const run = e => C.reduce(st, ev(e, (T += 1000)));
run({ t: 'join', by: 'p1', name: 'Fennel', emoji: '\u{1F98A}' });
run({ t: 'join', by: 'p2', name: 'Pip', emoji: '\u{1F438}' });
run({ t: 'join', by: 'p3', name: 'Moss', emoji: '\u{1F344}' });
t('three players joined', st.players.length, 3);
t('non-host cannot start', (run({ t: 'start', by: 'p2', seed: 'cat', secs: 25 }), st.status), 'lobby');
run({ t: 'start', by: 'p1', seed: 'cat', secs: 25 });
t('started, p1 first', [st.status, st.turnPid], ['playing', 'p1']);
run({ t: 'say', by: 'p2', pid: 'p2', idx: 0, text: 'hat' });
t('out-of-turn ignored', st.words.length, 0);
run({ t: 'say', by: 'p1', pid: 'p1', idx: 0, text: 'hat' });
t('p1 rhymes, rises, p2 next', [st.players[0].height, st.turnPid, st.turnIdx], [1, 'p2', 1]);
run({ t: 'say', by: 'p2', pid: 'p2', idx: 1, text: 'dog' });
t('non-rhyme via say ignored', st.words.length, 1);
run({ t: 'fail', by: 'p2', pid: 'p2', idx: 1, reason: 'wrong', text: 'dog' });
t('p2 bursts, p3 next', [st.players[1].alive, st.turnPid], [false, 'p3']);
run({ t: 'fail', by: 'p1', pid: 'p3', idx: 2, reason: 'timeout' });
t('early timeout ignored', st.players[2].alive, true);
C.reduce(st, ev({ t: 'fail', by: 'p1', pid: 'p3', idx: 2, reason: 'timeout' }, st.turnStart + 26000));
t('late timeout bursts p3, p1 wins', [st.status, st.winner], ['ended', 'p1']);
run({ t: 'reset', by: 'p2' });
t('play again -> lobby, everyone alive', [st.status, st.players.every(p => p.alive && p.height === 0)], ['lobby', true]);
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
